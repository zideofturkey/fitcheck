/**
 * GET /api/chat/conversations/:conversationId
 *
 * Get a specific conversation with messages.
 */
router.get("/conversations/:conversationId", async (req, res) => {
  try {
    const { conversationId } = req.params;
    const userId = req.user?.userId || "anonymous";
    const conversation = await conversationStore.getConversation(
      conversationId,
      userId,
    );

    if (!conversation) {
      return res.status(404).json({ error: "Conversation not found" });
    }

    res.json(conversation);
  } catch (error) {
    logger.error("Get conversation error:", error);
    res.status(500).json({ error: "Failed to get conversation" });
  }
});

/**
 * PATCH /api/chat/conversations/:conversationId
 *
 * Update conversation (e.g., title).
 */
router.patch("/conversations/:conversationId", async (req, res) => {
  try {
    const { conversationId } = req.params;
    const userId = req.user?.userId || "anonymous";
    const { title } = req.body;

    if (title !== undefined) {
      await conversationStore.updateTitle(conversationId, title, userId);
    }

    res.json({ success: true });
  } catch (error) {
    logger.error("Update conversation error:", error);
    res.status(500).json({ error: "Failed to update conversation" });
  }
});

/**
 * DELETE /api/chat/conversations/:conversationId
 *
 * Delete a conversation.
 */
router.delete("/conversations/:conversationId", async (req, res) => {
  try {
    const { conversationId } = req.params;
    const userId = req.user?.userId || "anonymous";
    await conversationStore.clearConversation(conversationId, userId);
    uuidAliasRegistry.clearConversationMap(conversationId);
    res.json({ success: true });
  } catch (error) {
    logger.error("Delete conversation error:", error);
    res.status(500).json({ error: "Failed to delete conversation" });
  }
});

