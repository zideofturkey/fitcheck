/**
 * GET /api/chat/status
 *
 * Get AI service status and configuration.
 */
router.get("/status", async (req, res) => {
  try {
    const status = chatService.getAIStatus();
    const mcpManager = req.app.get("mcpManager");
    const enhancedManager = new EnhancedMcpManager(mcpManager);

    res.json({
      ai: status,
      tools: {
        count: enhancedManager.getAllTools().length,
        mcpTools: mcpManager.getAllTools().length,
        builtInTools: 1 + VISUALIZATION_TOOLS.length, // docs search + visualization
        connections: mcpManager.getConnectionStatus(),
      },
      features: {
        documentationSearch: true,
        streaming: true,
        conversationHistory: true,
        uuidAliasMapping: aiService.UUID_ALIAS_ENABLED,
      },
      aliasRegistry: aiService.UUID_ALIAS_ENABLED
        ? uuidAliasRegistry.getRegistryStats()
        : {
            activeConversations: 0,
            totalAliases: 0,
            maxConversations: 0,
            ttlMs: 0,
          },
    });
  } catch (error) {
    logger.error("Status error:", error);
    res.status(500).json({ error: "Failed to get status" });
  }
});

